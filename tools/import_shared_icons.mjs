// Pulls the Everynote line icons shared with the Android app (art/shared-icons.json, produced by the Android repo's
// art/icons.py) into web/js/icons-shared.js, so both apps draw the same glyphs.
// Usage: node tools/import_shared_icons.mjs [path/to/icons.json]   (then: node tools/export_icons.mjs)
// Line icons are taken as they are (they already use currentColor). The coloured tool icons keep their shape but their main
// colour becomes currentColor, so the strip can still paint the pen / highlighter in the current ink colour; their lighter and
// darker shades become white / black overlays on top of it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] || path.join(root, 'art/shared-icons.json');
const shared = JSON.parse(fs.readFileSync(src, 'utf8'));
if (process.argv[2]) fs.copyFileSync(src, path.join(root, 'art/shared-icons.json'));

const rgb = h => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16) / 255);
const lum = h => { const [r, g, b] = rgb(h); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const sat = h => { const c = rgb(h); return Math.max(...c) - Math.min(...c); };
function tint(inner) {
  const paths = [...inner.matchAll(/<path d="([^"]+)" fill="(#[0-9A-Fa-f]{6})"\/>/g)];
  if (!paths.length) return inner;
  const main = paths[0][2];
  return paths.map(([, d, c]) => {
    if (c.toLowerCase() === main.toLowerCase()) return `<path d='${d}' fill='currentColor' stroke='none'/>`;
    if (sat(main) > 0.2 && sat(c) < 0.08 && (lum(c) < 0.3)) return `<path d='${d}' fill='${c}' stroke='none'/>`; // a neutral nib keeps its colour
    const dl = lum(c) - lum(main), a = Math.min(0.75, Math.abs(dl) * 1.6 + 0.1).toFixed(2);
    return `<path d='${d}' fill='currentColor' stroke='none'/><path d='${d}' fill='${dl > 0 ? '#FFFFFF' : '#000000'}' fill-opacity='${a}' stroke='none'/>`;
  }).join('');
}
const SKIP = new Set(['check_bold']); // the web app keeps its heavier check for swatches
const out = {};
for (const [name, inner] of Object.entries(shared)) {
  if (SKIP.has(name)) continue;
  const key = name.startsWith('tool_') ? name : 'ic_' + name;
  out[key] = name.startsWith('tool_') ? tint(inner) : inner.replace(/"/g, "'");
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n');
fs.writeFileSync(path.join(root, 'web/js/icons-shared.js'),
  `// GENERATED by tools/import_shared_icons.mjs from art/shared-icons.json (the Android app's line icon set). Do not edit.\nexport const SHARED_ICONS = {\n${body}\n};\n`);
console.log(Object.keys(out).length, 'shared icons');
